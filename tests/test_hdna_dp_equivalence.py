def test_ec_shorter_than_2minrep():
    """Sequence shorter than 2*minrep: no valid center exists."""
    assert hseeker.scan_sequence("AAAAAAAAAA", minrep=6, score=False) == []


def test_ec_all_n():
    """All-N sequence: no hits, no crash."""
    assert hseeker.scan_sequence("N" * 100, minrep=6, score=False) == []


def test_ec_single_n_at_right0():
    """N immediately at right0 — zero-length right arm, K_right_hard=0."""
    # center at pos 5, sp=0 → right0=6 = 'N' → hard stop immediately
    seq = "AAAAAANAAAAA"
    hits = hseeker.scan_sequence(seq, minrep=6, remove_overlaps=False, score=False)
    # No hit should have right_arm starting at position 7 (1-based index 6 in 0-based)
    for h in hits:
        assert h["right_arm"][0] != 'n', f"Hit starting at N: {h}"


def test_ec_n_left_only():
    """N on left side only — must NOT hard-stop; right arm still clean."""
    # If right arm alone would qualify, that's fine regardless of left-side N.
    # The C code only breaks on BT[right_char]==0, never on left char.
    seq = "NNNNNN" + "A" * 30
    # Run oracle to establish expected behavior
    params = dict(minrep=6, maxrep=50, maxspacer=5, purity=0.90, mismatch=0.10)
    c_hits = hseeker.scan_sequence(seq, remove_overlaps=False, score=False, **params)
    py_hits = oracle_scan(seq, **params)
    c_keys  = sorted(_hit_key(h) for h in c_hits)
    py_keys = sorted(_hit_key(h) for h in py_hits)
    assert c_keys == py_keys, (
        f"N-left-only mismatch: C={len(c_hits)} Oracle={len(py_hits)}"
    )


def test_ec_maxspacer_zero():
    """maxspacer=0: all returned hits must have spacer_length=0."""
