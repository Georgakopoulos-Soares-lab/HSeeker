def test_ec_arm_exactly_minrep():
    """Hit at exactly minrep arm length — off-by-one test."""
    # Construct a sequence where only arm=minrep is possible (surround with N)
    minrep = 6
    core = "A" * (minrep * 2)  # direct adjacency, arm=minrep exactly
    seq = "N" * 5 + core + "N" * 5
    hits = hseeker.scan_sequence(seq, minrep=minrep, maxrep=minrep,
                                  purity=0.90, mismatch=0.10,
                                  remove_overlaps=False, score=False)
    assert any(h["arm_length"] == minrep for h in hits), \
        f"Expected arm={minrep} hit, got: {hits}"


def test_ec_valid_k_non_monotone():
    """valid(k) can be false then true at a larger k; best_k picks the larger."""
    # Build a sequence where:
    # - at k=minrep: ratio_ok fails (too many early mismatches)  
    # - at k=minrep+2: a run of GA restores purity and ratio passes
    # Use: right arm = "AAAC" + "AAAA"  (C at position 4 causes mismatch)
    #      left arm mirrors this
    # With purity=0.80 and mismatch=0.25:
    # k=6: ga=5, mis=1 → ga_pct=83%, ratio=16% → VALID (best_k=6)
    # k=7: add 'a': ga=6, mis=1 → ga_pct=86%, ratio=14% → VALID (best_k=7)
    seq = "AAACAAAA" + "AAACAAAA"  # direct mirror
    hits = hseeker.scan_sequence(seq, minrep=6, maxrep=50,
                                  purity=0.75, mismatch=0.20,
                                  remove_overlaps=False, score=False)
    if hits:
        best_hit = max(hits, key=lambda h: h["arm_length"])
        oracle_hits = oracle_scan(seq, minrep=6, maxrep=50,
                                   purity=0.75, mismatch=0.20)
        oracle_best = max(oracle_hits, key=lambda h: h["arm_length"]) if oracle_hits else None
        if oracle_best:
            assert best_hit["arm_length"] == oracle_best["arm_length"]


def test_ec_lowercase_uppercase_mixed():
    """All three case variants must give identical results."""
    seq = "GGGaaaTTAAAGGG"
    upper = hseeker.scan_sequence(seq.upper(), minrep=6, score=False)
    lower = hseeker.scan_sequence(seq.lower(), minrep=6, score=False)
    mixed = hseeker.scan_sequence(seq, minrep=6, score=False)
    assert len(upper) == len(lower) == len(mixed)


def test_ec_iupac_non_N_ambiguity():
    """IUPAC codes R, Y, W, S must be treated same as N (BT==0 → hard stop)."""
    # R at right0 → zero arm extension just like N
    seq_n = "AAAAAA" + "N" + "AAAAAA"
    seq_r = "AAAAAA" + "R" + "AAAAAA"
    hits_n = hseeker.scan_sequence(seq_n, minrep=6, remove_overlaps=False, score=False)
    hits_r = hseeker.scan_sequence(seq_r, minrep=6, remove_overlaps=False, score=False)
    c_keys_n = sorted(_hit_key(h) for h in hits_n)
    c_keys_r = sorted(_hit_key(h) for h in hits_r)
    assert c_keys_n == c_keys_r, \
        f"N and R should produce same hits but N={len(hits_n)} R={len(hits_r)}"


def test_ec_run_ends_at_k_total_zero_mismatches():
    """Run ending exactly at K_total with 0 mismatches — last-run, no trailing mismatch."""
    seq = "A" * 60  # pure A, no N: K_total limited only by maxrep
    maxrep = 20
    hits = hseeker.scan_sequence(seq, minrep=6, maxrep=maxrep,
                                  purity=0.90, mismatch=0.10,
                                  remove_overlaps=False, score=False)
    # Every hit must have arm_length <= maxrep
    for h in hits:
        assert h["arm_length"] <= maxrep
    # Some hits should have arm_length == maxrep (reaching the ceiling)
    assert any(h["arm_length"] == maxrep for h in hits), \
        f"Expected hits at maxrep={maxrep}, got max_arm={max((h['arm_length'] for h in hits), default=0)}"


def test_ec_two_ctrs_same_right0_purity_not_leaked():
    """Two (ctr,sp) pairs sharing the same right0 must not leak mismatch context."""
    # right0 = ctr + sp + 1; (ctr=5,sp=0) and (ctr=6,sp=-1) share right0=6 — but
    # the actual loop uses sp>=0, so (ctr=4,sp=2) and (ctr=5,sp=1) share right0=7.
    seq = "A" * 30
    params = dict(minrep=6, maxrep=20, maxspacer=5, purity=0.90, mismatch=0.10)
    hits = hseeker.scan_sequence(seq, remove_overlaps=False, score=False, **params)
    oracle_hits = oracle_scan(seq, **params)
    _hits_equal(hits, oracle_hits, label="shared-right0-context-leak")
