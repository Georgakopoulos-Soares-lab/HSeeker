# ---------------------------------------------------------------------------
# Oracle: brute-force Python implementation of findHDNA_core's inner loop.
#
# This is the *independent* ground truth.  It must NOT be derived from or
# call the optimized code — it is a clean re-implementation of the spec
# from Section 1 of copilot_dp_optimization_instructions.md.
# ---------------------------------------------------------------------------

_BT = {}
for _b in "AGag":
    _BT[_b] = 1
for _b in "CTct":
    _BT[_b] = 2

def oracle_best_k(
    dna: str,
    ctr: int,
    sp: int,
    minrep: int,
    maxrep: int,
    purity_thresh: float,
    mismatch_tol: float,
) -> int:
    """Brute-force computation of best_k for a single (ctr, sp) pair.

    Exactly mirrors the C inner while-loop semantics from findHDNA_core:
      - Breaks immediately when right char has BT==0 (N / non-ACGT).
      - Left-side non-ACGT does NOT break the loop; it counts as a mismatch.
      - mismatch_budget is computed from maxrep (not running k).
      - Early-exit check is only inside k >= minrep block.
      - best_k = largest k in [minrep, K_final] where purity AND ratio valid.
    """
    total = len(dna)
    left_i  = ctr
    right_j = ctr + sp + 1
    k = 0
    mismatches = 0
    ga_count = 0
    ct_count = 0
    best_k = 0

    purity_thresh_int = int(purity_thresh * 100.0 + 0.5)
    mismatch_tol_int  = int(mismatch_tol  * 100.0 + 0.5)
    mismatch_budget   = int(mismatch_tol * maxrep)

    while left_i >= 0 and right_j < total and k < maxrep:
        lb = dna[left_i]
        bt_rb = _BT.get(dna[right_j], 0)

        if bt_rb == 0:
            break  # right-side non-ACGT: hard stop

        if lb != dna[right_j]:
            mismatches += 1
        k += 1

        if bt_rb == 1:
            ga_count += 1
        else:
            ct_count += 1

        if k >= minrep:
            ga_ok = ga_count * 100 >= purity_thresh_int * k
            ct_ok = ct_count * 100 >= purity_thresh_int * k
            ratio_ok = mismatches * 100 <= mismatch_tol_int * k
            if (ga_ok or ct_ok) and ratio_ok:
                best_k = k
            if mismatches > mismatch_budget:
                break

        left_i  -= 1
        right_j += 1

    return best_k


def oracle_scan(
    seq: str,
    minrep: int = 10,
    maxrep: int = 1000,
    maxspacer: int = 10,
    purity: float = 0.90,
    mismatch: float = 0.10,
) -> list[dict[str, Any]]:
    """Pure-Python oracle that replicates findHDNA_core output (no overlap removal).

    Returns a list of dicts with the same numeric fields as scan_sequence
    (start, end, arm_length, spacer_length, ga_pct, ct_pct, mirror_identity,
    is_perfect).  String fields (left_arm, spacer, right_arm, full_sequence)
    are also included for completeness.
    """
    dna = seq.lower()
    total = len(dna)
    hits = []

    purity_thresh_int = int(purity * 100.0 + 0.5)
    mismatch_tol_int  = int(mismatch * 100.0 + 0.5)

    for ctr in range(minrep - 1, total - minrep):
        if _BT.get(dna[ctr], 0) == 0:
            continue

        max_sp = min(maxspacer, total - minrep - ctr - 1)
        for sp in range(max_sp + 1):
            bk = oracle_best_k(dna, ctr, sp, minrep, maxrep, purity, mismatch)
            if bk < minrep:
                continue

            left_start  = ctr - bk + 1
            right_start = ctr + sp + 1

            # Recompute stats at best_k — left arm is accessed right-to-left
            # (dna[ctr], dna[ctr-1], ..., dna[left_start]) matched against
            # right arm left-to-right (dna[right_start], dna[right_start+1], ...)
            # t=0 → left=dna[ctr], right=dna[right_start]
            # t=1 → left=dna[ctr-1], right=dna[right_start+1], etc.
            mismatches = sum(
                1 for t in range(bk)
                if dna[ctr - t] != dna[right_start + t]
            )
            ga_count = sum(1 for t in range(bk) if _BT.get(dna[right_start + t], 0) == 1)
            ct_count = sum(1 for t in range(bk) if _BT.get(dna[right_start + t], 0) == 2)

            inv_k   = 1.0 / bk
            best_mir = 1.0 - mismatches * inv_k
            best_ga  = ga_count * inv_k
            best_ct  = ct_count * inv_k

            # is_perfect: uses exact float comparison (matches C float semantics
            # closely but Python floats are doubles — this may differ from C floats
            # for edge cases; the C code is the true oracle for is_perfect)
            is_perfect = ((best_ga == 1.0 or best_ct == 1.0) and best_mir == 1.0)

            spacer_str = dna[ctr + 1: ctr + sp + 1] if sp > 0 else "."
            left_arm   = dna[left_start: left_start + bk]
            right_arm  = dna[right_start: right_start + bk]
            full_seq   = left_arm + (spacer_str if sp > 0 else "") + right_arm

            hits.append({
                "start":           left_start + 1,
                "end":             right_start + bk,
                "arm_length":      bk,
                "spacer_length":   sp,
                "total_length":    bk * 2 + sp,
                "ga_pct":          best_ga * 100.0,
                "ct_pct":          best_ct * 100.0,
                "mirror_identity": best_mir * 100.0,
                "is_perfect":      is_perfect,
                "left_arm":        left_arm,
                "spacer":          spacer_str,
                "right_arm":       right_arm,
                "full_sequence":   full_seq,
            })
    return hits


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _float_close(a: float, b: float, tol: float = 1e-4) -> bool:
    return abs(a - b) <= tol


def _hit_key(h: dict) -> tuple:
    return (h["start"], h["end"], h["arm_length"], h["spacer_length"])


def _hits_equal(ref: list[dict], got: list[dict], label: str = "") -> None:
    """Assert two hit lists are field-by-field identical (order-independent)."""
    ref_keys = sorted(_hit_key(h) for h in ref)
    got_keys = sorted(_hit_key(h) for h in got)
    missing = set(ref_keys) - set(got_keys)
    extra   = set(got_keys) - set(ref_keys)
    assert not missing and not extra, (
        f"{label}: hit count mismatch ref={len(ref)} got={len(got)}\n"
        f"  missing from got: {list(missing)[:5]}\n"
        f"  extra in got:     {list(extra)[:5]}"
    )
    # Field-by-field check
    ref_map = {_hit_key(h): h for h in ref}
    got_map = {_hit_key(h): h for h in got}
    for key in ref_keys:
        r, g = ref_map[key], got_map[key]
        for field in ("arm_length", "spacer_length", "total_length",
                       "start", "end"):
            assert r[field] == g[field], (
                f"{label} key={key} field={field}: ref={r[field]} got={g[field]}"
            )
        for field in ("ga_pct", "ct_pct", "mirror_identity"):
            assert _float_close(r[field], g[field]), (
                f"{label} key={key} field={field}: ref={r[field]:.6f} got={g[field]:.6f}"
            )
        assert r["is_perfect"] == g["is_perfect"], (
            f"{label} key={key} is_perfect: ref={r['is_perfect']} got={g['is_perfect']}"
        )


