ORACLE_SPOT_SEQS = {
    "GAMIR_SEQ":   ("GGGAAATTAAAGGG",  dict(minrep=6,  maxrep=50,   maxspacer=10, purity=0.80, mismatch=0.20)),
    "CTMIR_SEQ":   ("CCCTTTAATTTCCC",  dict(minrep=6,  maxrep=50,   maxspacer=10, purity=0.80, mismatch=0.20)),
    "PERFECT_SEQ": ("A" * 14,           dict(minrep=6,  maxrep=50,   maxspacer=10, purity=0.90, mismatch=0.10)),
    "PURE_GA":     ("GAGAGAGAGAGAGAGAGAGAGA", dict(minrep=6, maxrep=50, maxspacer=10, purity=0.80, mismatch=0.20)),
    "all_A_50":    ("A" * 50,           dict(minrep=6,  maxrep=50,   maxspacer=5,  purity=0.90, mismatch=0.10)),
    "N_flanked":   ("N"*20 + "GGGAAATTAAAGGG" + "N"*20, dict(minrep=6, maxrep=50, maxspacer=10, purity=0.80, mismatch=0.20)),
    "mismatch0":   ("GGGAAATTAAAGGG",  dict(minrep=6,  maxrep=50,   maxspacer=10, purity=1.0,  mismatch=0.0)),
    "N_right0":    ("AAAAAA" + "N" + "AAAAAA", dict(minrep=6, maxrep=50, maxspacer=5, purity=0.90, mismatch=0.10)),
}


@pytest.mark.parametrize("name,seq_params", list(ORACLE_SPOT_SEQS.items()))
def test_oracle_matches_c_implementation(name, seq_params):
    """Python oracle must produce the same hit keys as scan_sequence (no overlap removal)."""
    seq, params = seq_params
    c_hits = hseeker.scan_sequence(seq, remove_overlaps=False, score=False, **params)
    py_hits = oracle_scan(seq, **params)

    c_keys  = sorted(_hit_key(h) for h in c_hits)
    py_keys = sorted(_hit_key(h) for h in py_hits)
    missing = set(c_keys) - set(py_keys)
    extra   = set(py_keys) - set(c_keys)
    assert not missing and not extra, (
        f"[{name}] Oracle/C mismatch: C={len(c_hits)} Oracle={len(py_hits)}\n"
        f"  In C but not oracle: {list(missing)[:5]}\n"
        f"  In oracle but not C: {list(extra)[:5]}"
    )
    # Numeric field check
    c_map  = {_hit_key(h): h for h in c_hits}
    py_map = {_hit_key(h): h for h in py_hits}
    for key in c_keys:
        c, p = c_map[key], py_map[key]
        for field in ("ga_pct", "ct_pct", "mirror_identity"):
            assert _float_close(c[field], p[field], tol=0.5), (
                f"[{name}] key={key} {field}: C={c[field]:.4f} Oracle={p[field]:.4f}"
            )


